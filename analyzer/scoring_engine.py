def compute_tfidf_similarity(resume_text: str, target_text: str) -> float:
    """
    Computes lexical cosine similarity between resume text and target profile/JD using TF-IDF n-grams.
    Accurately measures lexical vocabulary overlap and keyword frequency (not semantic understanding).
    Returns float between 0.0 and 1.0.
    """
    res = compute_lexical_tfidf_similarity(resume_text, target_text)
    return res["raw_similarity"]


def calculate_ats_readability(text: str) -> Dict[str, Any]:
    """
    Calculates readability and formatting health metrics completely offline
    without unvalidated remote network downloads.
    """
    words = re.findall(r'\b[a-zA-Z0-9_\'-]+\b', text)
    word_count = len(words)
    char_count = len(text)
    sentences = [s.strip() for s in re.split(r'[.!?]+', text) if s.strip()]
    sentence_count = max(1, len(sentences))

    # Fast, deterministic syllable counter (Flesch Reading Ease)
    def _count_syllables(word: str) -> int:
        w = word.lower()
        if len(w) <= 3:
            return 1
        w = re.sub(r'(?:[^laeiouy]|ed|es|e)$', '', w)
        w = re.sub(r'^y', '', w)
        syls = len(re.findall(r'[aeiouy]{1,2}', w))
        return max(1, syls)

    total_syllables = sum(_count_syllables(w) for w in words) if words else 0
    words_per_sentence = word_count / sentence_count
    syllables_per_word = (total_syllables / word_count) if word_count > 0 else 1.0

    # Flesch Reading Ease standard formula: 206.835 - 1.015 * (words/sentence) - 84.6 * (syllables/word)
    if word_count > 0:
        raw_flesch = 206.835 - (1.015 * words_per_sentence) - (84.6 * syllables_per_word)
        flesch_score = max(15.0, min(100.0, raw_flesch))
    else:
        flesch_score = 0.0

    # Readability health (ideal 40-75 for technical resumes)
    if 40 <= flesch_score <= 80:
        readability_status = "Optimal (Clear & Professional Technical Tone)"
        readability_rating = 95
    elif flesch_score > 80:
        readability_status = "Too Simple (Add more technical precision and depth)"
        readability_rating = 75
    else:
        readability_status = "Dense / Complex (Improve sentence conciseness and bullet readability)"
        readability_rating = 70

    # Length health (ideal 350 - 1100 words for standard 1-2 page technical resumes)
    if 350 <= word_count <= 1100:
        length_status = "Ideal (Standard 1 - 2 Pages)"
        length_score = 100
    elif word_count < 350:
        length_status = "Too Brief (Expand on technical achievements and project metrics)"
        length_score = 60
    else:
        length_status = "Too Long (Condense into 2 pages to prevent recruiter fatigue)"
        length_score = 75

    return {
        "word_count": word_count,
        "char_count": char_count,
        "sentence_count": sentence_count,
        "flesch_score": round(flesch_score, 1),
        "readability_status": readability_status,
        "readability_rating": readability_rating,
        "length_status": length_status,
        "length_score": length_score
    }


def find_benchmark_role(name: Optional[str]) -> str:
    """Safely resolves role name to an exact benchmark role key with fuzzy fallback."""
    if not name:
        return list(ROLE_BENCHMARKS.keys())[0]
    if name in ROLE_BENCHMARKS:
        return name
    clean_target = re.sub(r'[^\w\s]', '', name).lower().strip()
    # Check containment
    for role in ROLE_BENCHMARKS:
        clean_role = re.sub(r'[^\w\s]', '', role).lower().strip()
        if clean_target in clean_role or clean_role in clean_target:
            return role
    # Check significant keyword overlap
    for role in ROLE_BENCHMARKS:
        clean_role = re.sub(r'[^\w\s]', '', role).lower().strip()
        tokens_target = set(clean_target.split()) - {"engineer", "developer", "specialist", "scientist", "ai", "ml"}
        tokens_role = set(clean_role.split()) - {"engineer", "developer", "specialist", "scientist", "ai", "ml"}
        if tokens_target and tokens_target.intersection(tokens_role):
            return role
    return list(ROLE_BENCHMARKS.keys())[0]


def score_resume(
    resume_text: str,
    target_role_name: Optional[str] = None,
    custom_jd_text: Optional[str] = None
) -> Dict[str, Any]:
    """
    Main analytics scoring function.
    Evaluates resume against a role benchmark or a custom job description using a 6D defensible rubric:
    1. Core & Secondary Hard Skills (30%)
    2. Dense Transformer Semantic Embedding Fit (20%)
    3. Lexical TF-IDF Vocabulary Overlap (10%)
    4. Quantifiable Bullet Impact & Action Verbs (15%)
    5. MLOps & Production Readiness (10%)
    6. ATS Document Health & Completeness (15%)

    Returns comprehensive scores, subscores, radar dimensions, detailed explanations for every score component,
    and prominent rubric disclaimers.
    """
    if not resume_text or not resume_text.strip():
        return {
            "error": "Empty resume text provided",
            "composite_score": 0,
            "verdict": "⚠️ Empty File / Unreadable Document",
            "scores_breakdown": {},
            "explanations": {"general": "No readable content extracted from the resume file."}
        }

    # 1. Extract Candidate Skills
    extracted_skills_data = extract_skills_from_text(resume_text)
    candidate_skills = extracted_skills_data["all_matched"]
    candidate_by_category = extracted_skills_data["by_category"]

    # 2. Extract Sections, Contact Info & Impact
    sections = parse_resume_sections(resume_text)
    section_eval = evaluate_section_completeness(sections)
    contact_info = extract_contact_info(resume_text)
    impact_data = analyze_impact_and_verbs(resume_text)
    readability_data = calculate_ats_readability(resume_text)

    # 3. Determine Target Benchmark (Predefined Role vs Custom JD)
    if custom_jd_text and custom_jd_text.strip():
        jd_data = extract_skills_from_job_description(custom_jd_text)
        core_required = jd_data["core_skills"]
        secondary_required = jd_data["secondary_skills"]
        target_description = custom_jd_text
        role_label = "Custom Job Description"
        role_desc = "Tailored job description provided by recruiter or candidate."
    else:
        target_role_name = find_benchmark_role(target_role_name)
        benchmark = ROLE_BENCHMARKS[target_role_name]
        core_required = benchmark["core_skills"]
        secondary_required = benchmark["secondary_skills"]
        role_label = target_role_name
        role_desc = benchmark.get("description", "")
        target_description = benchmark["description"] + " " + " ".join(core_required + secondary_required)

    # 4. Compute Hard Skill Matches & Gaps
    matched_core = [s for s in core_required if s in candidate_skills]
    missing_core = [s for s in core_required if s not in candidate_skills]
    matched_secondary = [s for s in secondary_required if s in candidate_skills]
    missing_secondary = [s for s in secondary_required if s not in candidate_skills]

    target_all = set(core_required + secondary_required)
    bonus_skills = [s for s in candidate_skills if s not in target_all]

    core_match_rate = len(matched_core) / max(1, len(core_required))
    sec_match_rate = len(matched_secondary) / max(1, len(secondary_required))
    hard_skill_score = round((core_match_rate * 75 + sec_match_rate * 25), 1)

    # 5. Dual Semantic & Lexical Comparisons
    # A) Genuine Dense Vector Embedding Semantic Similarity
    semantic_dense_eval = compute_dense_embedding_similarity(resume_text, target_description)
    semantic_score = semantic_dense_eval["calibrated_score"]

    # B) Lexical TF-IDF Vocabulary Overlap (Accurately documented as lexical)
    lexical_eval = compute_lexical_tfidf_similarity(resume_text, target_description)
    lexical_score = lexical_eval["calibrated_score"]

    # 6. MLOps & Production Readiness Subscore
    mlops_candidate_skills = candidate_by_category.get("MLOps, Deployment & Infrastructure", [])
    mlops_score = min(100, int((len(mlops_candidate_skills) / 4) * 100))

    # 7. ATS Formatting & Completeness Score
    contact_score = 0
    if contact_info["email"]: contact_score += 35
    if contact_info["phone"]: contact_score += 25
    if contact_info["linkedin"] or contact_info["github"]: contact_score += 40

    ats_health_score = round(
        section_eval["score"] * 0.45 +
        contact_score * 0.30 +
        readability_data["readability_rating"] * 0.15 +
        readability_data["length_score"] * 0.10,
        1
    )

    # 8. Composite ATS Heuristic Score Calculation
    # Weights:
    # - Hard Skills: 30%
    # - Dense Semantic Embedding Fit: 20%
    # - Lexical TF-IDF Vocabulary Overlap: 10%
    # - Quantifiable Impact: 15%
    # - MLOps Readiness: 10%
    # - ATS Health & Structure: 15%
    composite_raw = (
        (hard_skill_score * 0.30) +
        (semantic_score * 0.20) +
        (lexical_score * 0.10) +
        (impact_data["overall_impact_score"] * 0.15) +
        (mlops_score * 0.10) +
        (ats_health_score * 0.15)
    )
    composite_score = max(0, min(100, int(round(composite_raw))))

    # 9. Defensible Score Explanations (Why each score was assigned)
    explanations = {
        "hard_skills": (
            f"Assigned {hard_skill_score}% based on matched core skills "
            f"({len(matched_core)}/{len(core_required)} = {core_match_rate*100:.0f}%, weight 75%) "
            f"and secondary skills ({len(matched_secondary)}/{len(secondary_required)} = {sec_match_rate*100:.0f}%, weight 25%). "
            f"Missing {len(missing_core)} critical requirements: {', '.join(missing_core[:4]) if missing_core else 'None'}."
        ),
        "semantic_similarity": (
            f"Assigned {semantic_score}% via dense transformer embeddings ({semantic_dense_eval['engine']}). "
            f"Raw cosine similarity: {semantic_dense_eval['raw_similarity']}. "
            "Measures genuine contextual alignment, synonymous role capabilities, and technical domain depth."
        ),
        "lexical_similarity": (
            f"Assigned {lexical_score}% via TF-IDF n-gram token overlap. "
            f"Raw cosine similarity: {lexical_eval['raw_similarity']}. "
            "Measures literal keyword matching and vocabulary frequency overlap with the job specification."
        ),
        "quantifiable_impact": (
            f"Assigned {impact_data['overall_impact_score']}% based on {len(impact_data.get('metrics_found', []))} quantifiable metrics "
            f"(percentages, monetary, latency, scale) and {len(impact_data.get('strong_verbs_found', []))} strong technical action verbs. "
            f"Demonstrates Google X-Y-Z formula achievement density."
        ),
        "mlops_readiness": (
            f"Assigned {mlops_score}% based on {len(mlops_candidate_skills)} detected production/MLOps competencies "
            f"({', '.join(mlops_candidate_skills[:4]) if mlops_candidate_skills else 'None detected'}). "
            "Evaluates candidate readiness to deploy, monitor, and scale models in production environments."
        ),
        "ats_health": (
            f"Assigned {ats_health_score}% factoring standard section segmentation ({section_eval['score']}%), "
            f"verified contact channels ({contact_score}%), readability score ({readability_data['flesch_score']}), "
            f"and resume length ({readability_data['word_count']} words, status: {readability_data['length_status']})."
        ),
        "composite_score": (
            f"Assigned composite score of {composite_score}% using the multi-dimensional weighted heuristic: "
            f"Hard Skills (30%) + Semantic Embeddings (20%) + Lexical Overlap (10%) + Impact (15%) + "
            f"MLOps (10%) + ATS Health (15%)."
        )
    }

    # Tier verdict
    if composite_score >= 85:
        verdict = "🏆 Elite Match (Interview Ready)"
        verdict_color = "#10B981"
        verdict_desc = "Strong candidate alignment across core technical competencies, verified bullet metrics, and ATS structure."
    elif composite_score >= 70:
        verdict = "🌟 Strong Match (High ATS Pass Rate)"
        verdict_color = "#3B82F6"
        verdict_desc = "Solid candidate profile. Bridging missing core skills and expanding quantifiable metrics will place you in the top tier."
    elif composite_score >= 50:
        verdict = "⚡ Moderate Fit (Needs Optimization)"
        verdict_color = "#F59E0B"
        verdict_desc = "Foundational background present, but several key role requirements or quantifiable metric achievements are missing."
    else:
        verdict = "⚠️ High Gap (Significant Optimization Needed)"
        verdict_color = "#EF4444"
        verdict_desc = "Low alignment against benchmark role requirements. Follow the recommended skill learning pathways and enrich experience bullets."

    # 10. Radar Chart Multi-Dimensional Data
    radar_dimensions = {
        "Core AI/ML Skills": hard_skill_score,
        "Semantic Fit (Dense)": semantic_score,
        "Lexical Fit (TF-IDF)": lexical_score,
        "Quantifiable Impact": impact_data["overall_impact_score"],
        "MLOps & Deployment": mlops_score,
        "ATS Health & Structure": ats_health_score
    }

    # 11. Curated Learning Recommendations
    learning_recommendations = []
    for skill in missing_core[:6]:
        resource = SKILL_LEARNING_RESOURCES.get(skill, {
            "title": f"Official {skill.title()} Documentation & Mastery",
            "link": f"https://www.google.com/search?q={skill.replace(' ', '+')}+tutorial+documentation"
        })
        learning_recommendations.append({
            "skill": skill,
            "title": resource["title"],
            "link": resource["link"],
            "priority": "High (Core Requirement)"
        })

    for skill in missing_secondary[:4]:
        resource = SKILL_LEARNING_RESOURCES.get(skill, {
            "title": f"Master {skill.title()} for Production AI",
            "link": f"https://www.google.com/search?q={skill.replace(' ', '+')}+guide"
        })
        learning_recommendations.append({
            "skill": skill,
            "title": resource["title"],
            "link": resource["link"],
            "priority": "Medium (Bonus Advantage)"
        })

    return {
        "target_role": role_label,
        "role_description": role_desc,
        "composite_score": composite_score,
        "verdict": verdict,
        "verdict_color": verdict_color,
        "verdict_desc": verdict_desc,
        "rubric_disclaimer": RUBRIC_DISCLAIMER,
        "scores_breakdown": {
            "hard_skill_score": hard_skill_score,
            "semantic_score": semantic_score,
            "semantic_embedding_score": semantic_score,
            "lexical_similarity_score": lexical_score,
            "lexical_tfidf_score": lexical_score,
            "impact_score": impact_data["overall_impact_score"],
            "mlops_score": mlops_score,
            "ats_health_score": ats_health_score
        },
        "explanations": explanations,
        "radar_dimensions": radar_dimensions,
        "skills_summary": {
            "matched_core": matched_core,
            "missing_core": missing_core,
            "matched_secondary": matched_secondary,
            "missing_secondary": missing_secondary,
            "bonus_skills": bonus_skills[:15],
            "total_candidate_skills": len(candidate_skills),
            "by_category": candidate_by_category
        },
        "impact_analysis": impact_data,
        "sections": sections,
        "section_evaluation": section_eval,
        "contact_info": contact_info,
        "readability": readability_data,
        "learning_recommendations": learning_recommendations,
        "model_metadata": {
            "dense_embedding_engine": semantic_dense_eval["engine"],
            "lexical_engine": lexical_eval["engine"]
        }
    }
